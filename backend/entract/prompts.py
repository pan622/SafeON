# -*- coding:utf-8 -*-
"""
SafeON KG Prompt V3

Node1:
危险因素抽取
仅输出:
Cause_Name
Cause_Type

Node2:
项目类型判断 + 风险等级判断
"""

from openai import OpenAI
try:
    from .config import API_KEY, BASE_URL, MODEL
except ImportError:
    from config import API_KEY, BASE_URL, MODEL
import json


client = OpenAI(
    api_key=API_KEY,
    base_url=BASE_URL,
    timeout=120
)


# =====================================================
# Node1 危险因素抽取 Prompt
# =====================================================

EXTRACT_PROMPT = r"""

你是一名施工现场安全风险知识图谱构建专家。


你需要识别：

施工过程中导致安全风险产生的具体危险因素。


==============================
危险因素定义
==============================

危险因素是指施工过程中可能导致安全事故的不安全状态、不安全行为、环境危险条件或管理缺陷。
若原文明确包含施工活动，应将施工活动融合到 Cause_Name 中；若未明确，不主动补充。

危险因素包括：

1. 人员因素

指人的不安全行为。作业人员自身行为

例如：

- 违章操作
- 未正确佩戴劳动防护用品
- 未按照要求进行作业


2. 物理/设备因素

指设备、机械、设施、结构、材料等客观危险状态。

例如：

- 设备超载
- 机械故障


3. 环境因素

指施工环境导致的危险条件。

例如：

- 地质条件不良
- 空间环境受限
- 排水措施不足


4. 管理因素

指施工组织和安全管理缺陷。

例如：

- 专项施工方案缺失
- 安全管理不到位
- 安全检查不足
- 施工单位、管理制度、方案流程缺失

==============================
人员因素与管理因素区分规则
==============================

- 土方开挖顺序、方法不符合设计工况
- 回填土参数控制不足
- 未按施工方案要求施工
- 未开展危险源辨识和风险评价
- 设备设施未经验收投入使用
上述问题应优先归入管理因素。
只有当文本明确描述个人违规行为时，才归入人员因素。

==============================
重点规则：规范文本解析
==============================

输入文本可能来自：

- 国家规范
- 行业标准
- 施工方案
- 安全管理文件


规范中的强制性要求需要转换为危险因素。


1.

“严禁XXX”

转换为：

XXX危险行为



2.

“应设置XXX”
“应采取XXX措施”

如果该措施用于防止事故，

转换为：

XXX防护措施缺失

3.

“超过XXX限值”

转换为：

超限危险状态


示例：

原文：
吊装作业严禁超载。

抽取：
Cause_Name:
起重设备超载吊装

原文：
荷载不得超过设计要求。

抽取：
Cause_Name:
施工荷载超过设计限值



==============================
禁止抽取内容
==============================

不要抽取事故类型与普通对象：

例如：

- 高处坠落
- 物体打击
- 起重伤害
- 坍塌
- 机械伤害
- 塔吊
- 脚手架
- 模板

这些属于事故结果或项目，不属于危险因素。


除非文本描述其危险状态。


例如：

错误：

塔吊


正确：

塔吊超载运行


==============================
危险因素合并规则
==============================

对于同一句或相邻文本中，描述同一风险状态的多个相似危险因素，可以适当合并为一个更完整的危险因素。



==============================
输出要求
==============================

只输出危险因素。

输出格式：

{
"hazards":[
{
"Cause_Name":"",
"Cause_Type":""
}
]
}


如果没有危险因素：

{
"hazards":[]
}


输出必须是合法JSON。

禁止输出：

- 解释文字
- 分析过程
- Markdown
- ```json代码块

输出内容必须能够直接被Python json.loads()解析。

"""


def extract_hazard(text):

    response = client.chat.completions.create(
        model=MODEL,
        temperature=0,
        extra_body={
            "thinking": {
                "type": "disabled"
            }
        },
        messages=[
            {
                "role":"system",
                "content":EXTRACT_PROMPT
            },
            {
                "role":"user",
                "content":text
            }
        ]
    )

    return json.loads(
        response.choices[0].message.content
    )



# =====================================================
# Node2 项目类型+风险等级
# =====================================================

CLASSIFY_PROMPT = r"""

你是一名施工安全风险评估专家。

根据输入的多个危险因素，
逐个判断其所属施工活动和风险等级。
按输入危险因素顺序逐项返回，不得遗漏或新增。
输入为危险因素列表：

[
{
"Cause_Name":"危险因素名称",
"Cause_Type":"危险因素类别"
}
]

请保持每个危险因素独立判断，不要合并不同危险因素。


==============================
Project_Name
==============================

选择：

基坑工程

高处作业

临时用电

模板工程

脚手架工程

起重吊装

施工机械

有限空间

动火消防

拆除工程

地下工程

运输及材料管理

通用安全管理


如果判断不在这几类施工项目中：
填写：
其他施工活动


若危险因素没有明显专项工程属性，
且适用于多数施工活动，
应归入通用安全管理。

例如：
- 未进行安全技术交底
- 安全检查不足


==============================
Cause_Level
==============================

重大风险：

可能导致群死群伤、
重大结构失稳、
重大工程事故。


较大风险：

可能造成严重伤害。


一般风险：

存在明显安全隐患，
需要采取控制措施。


低风险：

危险程度较低。


==============================
输出
==============================

{
"result":[
{
"Project_Name":"",
"Cause_Level":""
}
]
}

输出必须是合法JSON。

禁止输出：

- 解释文字
- 分析过程
- Markdown
- ```json代码块

输出内容必须能够直接被Python json.loads()解析。

"""


def classify_risk(hazard):

    response = client.chat.completions.create(
        model=MODEL,
        temperature=0,
        extra_body={
            "thinking": {
                "type": "disabled"
            }
        },
        messages=[
            {
                "role":"system",
                "content":CLASSIFY_PROMPT
            },
            {
                "role":"user",
                "content":json.dumps(
                    hazard,
                    ensure_ascii=False
                )
            }
        ]
    )

    return json.loads(
        response.choices[0].message.content
    )
